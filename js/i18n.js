  var EN = {};       // captured from the page on first run
  var EN_ATTR = {};
  var current = "en";
  var listeners = [];

  function detect() {
    try {
      var saved = localStorage.getItem("tt-lang");
      if (saved === "en" || saved === "pt") return saved;
    } catch (e) {}
    var langs = navigator.languages || [navigator.language || "en"];
    return String(langs[0] || "en").toLowerCase().indexOf("pt") === 0 ? "pt" : "en";
  }

  function capture() {
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      EN[el.getAttribute("data-i18n")] = el.innerHTML;
    });
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      var parts = el.getAttribute("data-i18n-attr").split(":");
      EN_ATTR[parts[1]] = el.getAttribute(parts[0]) || "";
    });
  }

  function apply(lang) {
    current = lang;
    var dict = lang === "pt" ? PT : EN;
    document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      var parts = el.getAttribute("data-i18n-attr").split(":");
      var val = lang === "pt" ? PT[parts[1]] : EN_ATTR[parts[1]];
      if (val !== undefined) el.setAttribute(parts[0], val);
    });

    listeners.forEach(function (fn) { fn(lang); });
  }

  function set(lang) {
    try { localStorage.setItem("tt-lang", lang); } catch (e) {}
    apply(lang);
  }

